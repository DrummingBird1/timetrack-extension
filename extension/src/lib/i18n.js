// Per-language text direction and Intl locale tag. Extend this whenever a new
// language is added to DICT — dir()/locale() key off it instead of a hardcoded
// he-is-the-only-RTL-language binary.
const LANG_META = {
  he: { dir: 'rtl', locale: 'he-IL' },
  en: { dir: 'ltr', locale: 'en-US' },
  ar: { dir: 'rtl', locale: 'ar' },
  ru: { dir: 'ltr', locale: 'ru-RU' },
  es: { dir: 'ltr', locale: 'es' },
  fr: { dir: 'ltr', locale: 'fr-FR' },
};

export function setLang(l) {
  lang = DICT[l] ? l : 'he';
  setDurationLocale(lang);
}

export function getLang() {
  return lang;
}

export function dir() {
  return (LANG_META[lang] || LANG_META.he).dir;
}

export function locale() {
  return (LANG_META[lang] || LANG_META.he).locale;
}

export function categoryLabel(key) {
  return t(`category.${key}`);
}

export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]);
  if (s == null) s = DICT.he[key];
  if (s == null) s = key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(vars[k]);
  return s;
}

/** Fill all [data-i18n] text and [data-i18n-ph]/[data-i18n-title] attributes. */
export function localize(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
